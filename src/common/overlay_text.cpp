const char* Tr(const char* en) {
    if (!en) return en;
    uint32_t l = Lang();
    if (l == 9) {
        static const std::unordered_map<std::string, const char*> pt = [] {
            std::unordered_map<std::string, const char*> m;
            for (size_t i = 0; i < kPtRowCount; i++) m.emplace(kPtRows[i].en, kPtRows[i].pt);
            return m;
        }();
        auto it = pt.find(en);
        return it == pt.end() ? en : it->second;
    }
    if (l == 10) {
        static const std::unordered_map<std::string, const char*> ru = [] {
            std::unordered_map<std::string, const char*> m;
            for (size_t i = 0; i < kRuRowCount; i++) m.emplace(kRuRows[i].en, kRuRows[i].pt);
            return m;
        }();
        auto it = ru.find(en);
        return it == ru.end() ? en : it->second;
    }
    if (l == 11) {
        static const std::unordered_map<std::string, const char*> pl = [] {
            std::unordered_map<std::string, const char*> m;
            for (size_t i = 0; i < kPlRowCount; i++) m.emplace(kPlRows[i].en, kPlRows[i].pt);
            return m;
        }();
        auto it = pl.find(en);
        return it == pl.end() ? en : it->second;
    }
    int col = l == 4 ? 1 : l == 6 ? 2 : l == 5 ? 3 : 0;
    if (!col) return en;
    static const std::unordered_map<std::string, const Row*> index = [] {
        std::unordered_map<std::string, const Row*> m;
        for (const Row& r : kRows) m.emplace(r.en, &r);
        return m;
    }();
    auto it = index.find(en);
    if (it == index.end()) return en;
    const Row& r = *it->second;
    return col == 1 ? r.fr : col == 2 ? r.it : r.es;
}

std::string Tr(const std::string& en) { return Tr(en.c_str()); }

